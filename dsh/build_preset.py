"""Build the `flac3d` agent preset from the shipped `standard` composition.

Presets are snapshots by design (an upgrade never rewrites a local preset), so
this script exists to make the snapshot reproducible and reviewable rather than
to run at install time.

It applies exact-match replacements and aborts if any pattern does not match
exactly once -- a silent partial edit in an agent composition produces a preset
that mounts but contributes nothing, which is far more expensive to debug than
a failed build.

Usage:
    python build_preset.py <standard_agent.cordis.yml> <out_dir>
"""
import io
import os
import sys

# --- replacement 1: persona prefix gains the FLAC3D operating rules ---------
OLD_PERSONA = """    prefix: >-
      You are a coding agent powered by the {{model}} model.
"""

NEW_PERSONA = """    prefix: |-
      You are a coding agent powered by the {{model}} model, working with ITASCA FLAC3D.

      FLAC3D is driven through the `mcp__flac3d__*` tools. Three rules override any instinct to improvise:

      1. FLAC3D solves on ONE thread in ONE process. Cases run strictly serially, and `model new` destroys the current model. Never submit two cases concurrently.
      2. Long-running work goes through `flac_execute_task`, never `flac_execute_code`; the latter blocks until it times out.
      3. FISH runs on Python 3.6 and its trigonometry is in RADIANS. Use `angle * math.pi / 180.0`; `math.deg2rad` does not exist. Feeding degrees to `math.sin` returns a wrong number silently rather than raising.

      Before writing or editing a FLAC3D model, a parameter mapping, or a run script, load the `flac3d-simulation` skill.
"""

# --- replacement 2: the preset carries its own skill ------------------------
# `baseUrl` is the preset's own directory, so the root resolves wherever the
# preset is installed. This mirrors the shipped `cordis` preset.
OLD_SKILL = """- id: skill-filesystem
  name: '@deepseek-ai/dsh-skill-filesystem'
"""

NEW_SKILL = """- id: skill-filesystem
  name: '@deepseek-ai/dsh-skill-filesystem'
  config:
    customSkillDirs:
      - !!js "process.getBuiltinModule('node:url').fileURLToPath(new URL('skills/', baseUrl))"
"""

REPLACEMENTS = [
    ("persona prefix", OLD_PERSONA, NEW_PERSONA),
    ("skill-filesystem customSkillDirs", OLD_SKILL, NEW_SKILL),
]

# Written above the snapshot so anyone diffing the file knows it is generated,
# not hand-edited, and where it came from.
PROVENANCE = """# PROVENANCE: snapshot of the DSH `standard` agent preset, regenerated by
# dsh/build_preset.py with the persona and skill-filesystem rows replaced (see
# NOTICE). Rebuild rather than hand-edit, so the diff stays reviewable.
#
"""


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, out_dir = sys.argv[1], sys.argv[2]

    with io.open(src, "r", encoding="utf-8") as fh:
        text = fh.read()

    for label, old, new in REPLACEMENTS:
        n = text.count(old)
        if n != 1:
            print("ABORT: pattern %r matched %d times, expected exactly 1" % (label, n))
            return 1
        text = text.replace(old, new)
        print("OK  %-34s replaced 1 occurrence" % label)

    os.makedirs(out_dir, exist_ok=True)
    dest = os.path.join(out_dir, "agent.cordis.yml")
    with io.open(dest, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(PROVENANCE + text)
    print("wrote %s (%d lines)" % (dest, text.count("\n") + 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
